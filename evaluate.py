"""Evaluation script for the TelecomPlus support agent.

This script evaluates the agent's responses against the expected answers
from the evaluation dataset using LLM-as-a-judge methodology.
"""

import json
import re

import pandas as pd
from langchain_google_genai import ChatGoogleGenerativeAI

from src.config import LLM_MODEL
from src.main import answer


def evaluate_response(question: str, expected_answer: str, agent_answer: str, llm) -> dict:
    """Evaluate the relevance of the agent's answer using LLM-as-a-judge.

    Args:
        question: The customer question
        expected_answer: The expected answer from the dataset
        agent_answer: The answer generated by your agent
        llm: The LLM instance to use as judge

    Returns:
        dict: Contains 'score' (0-5) and 'reasoning' (explanation)
    """
    evaluation_prompt = f"""You are an expert evaluator for a customer support chatbot.

Question: {question}

Expected Answer: {expected_answer}

Agent's Answer: {agent_answer}

Evaluate the agent's answer based on:
1. Accuracy: Does it provide correct information?
2. Completeness: Does it address all parts of the question?
3. Relevance: Is the response relevant to the question?
4. Clarity: Is it clear and understandable?

Provide a score from 0 to 5:
- 5: Perfect answer, accurate and complete
- 4: Very good, minor issues
- 3: Acceptable, some missing information
- 2: Partial answer, significant issues
- 1: Poor answer, mostly incorrect
- 0: Completely wrong or irrelevant

Respond ONLY with a JSON object in this exact format:
{{"score": <number 0-5>, "reasoning": "<brief explanation>"}}"""

    try:
        response = llm.invoke(evaluation_prompt)
        response_text = response.content.strip()
        
        # Try to extract JSON from response
        json_match = re.search(r'\{.*\}', response_text, re.DOTALL)
        if json_match:
            result = json.loads(json_match.group())
            return {
                "score": int(result.get("score", 0)),
                "reasoning": result.get("reasoning", "No reasoning provided")
            }
        else:
            # Fallback if JSON parsing fails
            return {"score": 3, "reasoning": "Unable to parse LLM response"}
    except Exception as e:
        print(f"Error in evaluation: {e}")
        return {"score": 0, "reasoning": f"Evaluation error: {str(e)}"}


def run_evaluation():
    """Run evaluation on all questions from the evaluation dataset."""

    # Initialize LLM for evaluation
    print("Initializing LLM judge...")
    llm = ChatGoogleGenerativeAI(model=LLM_MODEL, temperature=0)

    # Load evaluation questions
    print("Loading evaluation questions...")
    df = pd.read_excel("data/evaluation_questions.xlsx")

    print(f"Loaded {len(df)} questions\n")
    print("=" * 80)

    results = []
    total_score = 0
    max_score = 0
    
    # Track scores by difficulty
    scores_by_difficulty = {"Facile": [], "Moyen": [], "Difficile": [], "Très Difficile": []}

    # Evaluate each question
    for idx, row in df.iterrows():
        question = row["Question"]
        expected_answer = row["Réponse Attendue"]
        difficulty = row["Difficulté"]
        client_id = row.get("Client_ID", None)

        print(f"\nQuestion {idx + 1}/{len(df)} [{difficulty}]:")
        print(f"Q: {question}")

        # Get agent's answer with client_id if available
        try:
            if pd.notna(client_id):
                agent_answer = answer(question, client_id=str(int(client_id)))
            else:
                agent_answer = answer(question)
        except Exception as e:
            agent_answer = f"Error: {str(e)}"
            
        print(f"Agent: {agent_answer[:200]}..." if len(agent_answer) > 200 else f"Agent: {agent_answer}")

        # Evaluate the response using LLM-as-a-judge
        eval_result = evaluate_response(question, expected_answer, agent_answer, llm)
        score = eval_result["score"]
        reasoning = eval_result["reasoning"]
        
        total_score += score
        max_score += 5
        scores_by_difficulty[difficulty].append(score)

        print(f"Score: {score}/5")
        print(f"Reasoning: {reasoning}")

        # Store results
        results.append({
            "Question": question,
            "Expected Answer": expected_answer,
            "Agent Answer": agent_answer,
            "Difficulty": difficulty,
            "Score": score,
            "Reasoning": reasoning
        })

        print("-" * 80)

    # Calculate final metrics
    accuracy = (total_score / max_score) * 100 if max_score > 0 else 0
    print("\n" + "=" * 80)
    print("EVALUATION RESULTS")
    print("=" * 80)
    print(f"Total questions: {len(df)}")
    print(f"Total score: {total_score}/{max_score}")
    print(f"Overall accuracy: {accuracy:.2f}%")
    print(f"Average score: {total_score/len(df):.2f}/5")
    
    # Print breakdown by difficulty
    print("\nBreakdown by difficulty:")
    for diff in ["Facile", "Moyen", "Difficile", "Très Difficile"]:
        if scores_by_difficulty[diff]:
            avg = sum(scores_by_difficulty[diff]) / len(scores_by_difficulty[diff])
            print(f"  {diff}: {avg:.2f}/5 ({len(scores_by_difficulty[diff])} questions)")

    # Save results to Excel
    results_df = pd.DataFrame(results)
    results_df.to_excel("evaluation_results.xlsx", index=False)
    print("\nResults saved to: evaluation_results.xlsx")


if __name__ == "__main__":
    run_evaluation()
